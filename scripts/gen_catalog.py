#!/usr/bin/env python3
"""Generate docs/TOOL_CATALOG.md and the per-skill filter-mapping copies.

Sources of truth (imported, never parsed):
- `maitabi.registry.ACTIONS` — actions, endpoints, docs, help
- `maitabi.core.inputs` models (via `registry`) — every parameter
- `cli/fields.plan_field` — the real CLI flags/defaults shown in the catalog
- `skills/maitabi-bus-extractor/references/filter-mapping.md` — copied into
  the `maitabi-cli` and `maitabi-mcp` skills so each skill works standalone
  with `npx skills add` (a skill's files must not reach outside its folder).

Usage:
    python scripts/gen_catalog.py           # rewrite outputs
    python scripts/gen_catalog.py --check   # exit 1 if outputs are stale (CI)
"""

import argparse
import sys
from enum import IntEnum
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

CATALOG_PATH = ROOT / "docs" / "TOOL_CATALOG.md"
FILTER_SOURCE = ROOT / "skills" / "maitabi-bus-extractor" / "references" / "filter-mapping.md"
FILTER_TARGETS = (
    ROOT / "skills" / "maitabi-cli" / "references" / "filter-mapping.md",
    ROOT / "skills" / "maitabi-mcp" / "references" / "filter-mapping.md",
)

GENERATED_NOTE = (
    "> Generated by `scripts/gen_catalog.py` from `src/maitabi/registry.py` "
    "and `core/inputs.py` — do not edit by hand. Run `make catalog` to regenerate; "
    "`make catalog-check` (CI) fails when this file is stale."
)


def _annotation_text(annotation) -> str:
    """Render a model annotation for humans: `Optional[int]` → `int | null`."""
    from maitabi.cli.fields import annotation_members

    def fmt(member) -> str:
        if member is type(None):
            return "null"
        if isinstance(member, type):
            if issubclass(member, IntEnum):
                return "int"
            return member.__name__  # int / str / bool
        return str(member).replace("typing.", "")  # list[int]

    return " | ".join(fmt(member) for member in annotation_members(annotation))


def _default_text(info) -> str:
    if info.is_required():
        return "**required**"
    default = info.default
    if default is None:
        return "—"
    if isinstance(default, bool):
        return "true" if default else "false"
    if isinstance(default, IntEnum):
        return str(int(default))
    if isinstance(default, str):
        return f"`{default}`"
    return str(default)


def _service_name(service) -> str:
    return getattr(service, "__name__", str(service))


def render_catalog() -> str:
    from maitabi.cli.fields import plan_field
    from maitabi.registry import ACTIONS

    lines: list[str] = ["# Maitabi Tool Catalog", "", GENERATED_NOTE, ""]

    lines += [
        "## Actions (7)",
        "",
        "| Domain | MCP Tool | CLI Command | Input Model | Service | Endpoint |",
        "|---|---|---|---|---|---|",
    ]
    for action in ACTIONS:
        lines.append(
            f"| `{action.domain}` | `{action.tool}` | `maitabi {action.domain} {action.command}` "
            f"| `{action.input_model.__name__}` | `{_service_name(action.service)}` | `{action.endpoint}` |"
        )
    lines.append("")

    lines += [
        "## Parameters (per action)",
        "",
        "The MCP tool argument and the model field share the same name; the CLI",
        "flag is the kebab-case form of it.",
        "",
    ]
    for action in ACTIONS:
        lines += [
            f"### `{action.tool}` · `maitabi {action.domain} {action.command}`",
            "",
            f"Endpoint: `{action.endpoint}`",
            "",
            action.doc.replace("\n\n", "\n\n> "),
            "",
            "| Field (MCP arg) | CLI flag | Type | Default | Description |",
            "|---|---|---|---|---|",
        ]
        for name, info in action.input_model.model_fields.items():
            plan = plan_field(name, info)
            if plan.store_true:
                type_text = "bool flag"
            elif plan.choices is not None:
                type_text = "int {" + ",".join(str(c) for c in plan.choices) + "}"
            else:
                # Escape the union pipe or it would split the table cell.
                type_text = f"`{_annotation_text(info.annotation)}`".replace("|", "\\|")
            description = (info.description or "").replace("|", "\\|")
            lines.append(f"| `{name}` | `{plan.flag}` | {type_text} | {_default_text(info)} | {description} |")
        lines.append("")

    lines += [
        "## CLI exit codes",
        "",
        "| Code | Meaning |",
        "|---|---|",
        "| 0 | Success |",
        "| 1 | Upstream/network error (result payload contains `error`) |",
        "| 2 | Input error (bad flag value, failed model validation) |",
        "",
    ]
    return "\n".join(lines)


def collect_outputs() -> dict[Path, str]:
    """All generated files: catalog + identical filter-mapping copies."""
    outputs = {CATALOG_PATH: render_catalog()}
    filter_text = FILTER_SOURCE.read_text(encoding="utf-8")
    for target in FILTER_TARGETS:
        outputs[target] = filter_text
    return outputs


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify committed outputs match the sources (exit 1 when stale)",
    )
    args = parser.parse_args(argv)

    outputs = collect_outputs()
    stale = [
        path for path, content in outputs.items() if not path.exists() or path.read_text(encoding="utf-8") != content
    ]

    if args.check:
        if stale:
            for path in stale:
                print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
            print("run `make catalog` and commit the result", file=sys.stderr)
            return 1
        print("catalog up to date")
        return 0

    for path, content in outputs.items():
        if path.exists() and path.read_text(encoding="utf-8") == content:
            print(f"unchanged: {path.relative_to(ROOT)}")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote: {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
